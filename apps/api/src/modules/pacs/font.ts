/** Draws `text` (unknown characters become spaces) at x,y with an integer scale. */
export function drawText(
  pixels: Uint8Array,
  width: number,
  text: string,
  x: number,
  y: number,
  scale = 2,
  value = 255,
) {
  const height = pixels.length / width;
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const glyph = GLYPHS[ch] ?? GLYPHS[' ']!;
    for (let gy = 0; gy < 7; gy++) {
      for (let gx = 0; gx < 5; gx++) {
        if (glyph[gy]![gx] !== '1') continue;
        for (let sy = 0; sy < scale; sy++) {
          for (let sx = 0; sx < scale; sx++) {
            const px = cx + gx * scale + sx;
            const py = y + gy * scale + sy;
            if (px >= 0 && px < width && py >= 0 && py < height) pixels[py * width + px] = value;
          }
        }
      }
    }
    cx += 6 * scale;
  }
}

export const textWidth = (text: string, scale = 2) => text.length * 6 * scale;
